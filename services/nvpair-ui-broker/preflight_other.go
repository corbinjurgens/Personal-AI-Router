//go:build !windows

package main

import (
	"fmt"
	"net"
)

// The proxy's real bind remains authoritative if another process wins the race.
func tcpPortAvailable(port int) bool {
	ln, err := net.Listen("tcp", fmt.Sprintf(":%d", port))
	if err != nil {
		return false
	}
	_ = ln.Close()
	return true
}
